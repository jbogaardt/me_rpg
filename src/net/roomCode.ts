const WORD = /^[a-z]+$/;
const adjectives = new Set(ADJECTIVES);
const nouns = new Set(NOUNS);

/** A fresh code. `randomInt(n)` must return a uniform integer in [0, n); the relay passes a crypto-backed one. */
export function randomCode(randomInt: (n: number) => number): string {
  const adjective = ADJECTIVES[randomInt(ADJECTIVES.length)];
  const noun = NOUNS[randomInt(NOUNS.length)];
  return `${adjective}-${noun}`;
}

/**
 * The canonical form of whatever was typed ("Mighty Apples", " mighty_apples ", "MIGHTY-APPLES"), or null when it
 * isn't a code the relay could have issued. Words are checked against the lists so a typo is caught on the
 * device instead of costing a round trip, and so the relay never creates storage for made-up names.
 */
export function normalizeCode(input: string): string | null {
  const parts = input
    .trim()
    .toLowerCase()
    .split(/[^a-z]+/)
    .filter(Boolean);
  const [adjective, noun, ...rest] = parts;
  if (!adjective || !noun || rest.length > 0 || !WORD.test(adjective) || !WORD.test(noun)) return null;
  return adjectives.has(adjective) && nouns.has(noun) ? `${adjective}-${noun}` : null;
}

/** The game code in a join link's hash (`#join=mighty-apples`), or null. */
export function codeFromHash(hash: string): string | null {
  const match = /^#join=([^&\s]+)/.exec(hash);
  if (!match?.[1]) return null;
  try {
    return normalizeCode(decodeURIComponent(match[1]));
  } catch {
    return null;
  }
}

/** The shareable link that opens the game already set up to join `code`. */
export function joinLink(base: string, code: string): string {
  return `${base}#join=${code}`;
}
